import { resolve } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';

export interface GenerateOptions {
  /** Absolute path of the OpenAPI document. */
  readonly input: string;
  /** Compare instead of write. */
  readonly check: boolean;
}

export type ParseResult =
  | { readonly ok: true; readonly value: GenerateOptions }
  | { readonly ok: false; readonly error: string };

const USAGE = 'usage: generate --input <openapi.json> [--check]';

/** Parses the command line; relative `--input` paths resolve against `cwd`. */
export function parseArguments(argv: readonly string[], cwd: string = process.cwd()): ParseResult {
  let input: string | undefined;
  let check = false;
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === '--') {
      continue;
    }
    if (argument === '--check') {
      check = true;
    } else if (argument === '--input') {
      index += 1;
      const value = argv[index];
      if (value === undefined || value.startsWith('--')) {
        return { ok: false, error: `--input needs a path; ${USAGE}` };
      }
      input = value;
    } else {
      return { ok: false, error: `unknown argument ${JSON.stringify(argument)}; ${USAGE}` };
    }
  }
  if (input === undefined) {
    return { ok: false, error: `missing --input; ${USAGE}` };
  }
  return { ok: true, value: { input: resolve(cwd, input), check } };
}

const HEADER =
  '/* Generated by scripts/generate.ts from the OpenAPI document of `app`. Do not edit. */\n';

/** Renders the `paths`/`components` declarations for the OpenAPI document at `source`. */
export async function generateSchema(source: URL): Promise<string> {
  const ast = await openapiTS(source, { alphabetize: true, immutable: true });
  return `${HEADER}${astToString(ast)}`;
}

import { spawnSync } from 'node:child_process';
import { readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { describe, expect, it } from 'vitest';
import { generateSchema, parseArguments } from '../scripts/generate-lib.ts';

const fixture = resolve(import.meta.dirname, 'fixtures/openapi.json');
const script = resolve(import.meta.dirname, '../scripts/generate.ts');
const generatedFile = resolve(import.meta.dirname, '../src/generated/schema.d.ts');
const usage = 'usage: generate --input <openapi.json> [--check]';

describe('parseArguments', () => {
  it('resolves a relative input against the working directory', () => {
    const result = parseArguments(['--input', 'openapi.json'], resolve('/work'));
    expect(result).toEqual({
      ok: true,
      value: { input: resolve('/work', 'openapi.json'), check: false },
    });
  });

  it('accepts --check and a leading -- from pnpm', () => {
    const result = parseArguments(['--', '--input', fixture, '--check']);
    expect(result).toEqual({ ok: true, value: { input: fixture, check: true } });
  });

  it('requires --input', () => {
    expect(parseArguments([])).toEqual({ ok: false, error: `missing --input; ${usage}` });
    expect(parseArguments(['--check'])).toEqual({ ok: false, error: `missing --input; ${usage}` });
  });

  it.each([[['--input']], [['--input', '--check']]])(
    'requires a path after --input: %j',
    (argv) => {
      expect(parseArguments(argv)).toEqual({
        ok: false,
        error: `--input needs a path; ${usage}`,
      });
    },
  );

  it('rejects unknown arguments', () => {
    expect(parseArguments(['--input', fixture, '--force'])).toEqual({
      ok: false,
      error: `unknown argument "--force"; ${usage}`,
    });
  });
});

describe('generateSchema', () => {
  it('declares the paths of the document', async () => {
    const schema = await generateSchema(pathToFileURL(fixture));
    expect(schema.startsWith('/* Generated by scripts/generate.ts')).toBe(true);
    expect(schema).toContain('export interface paths');
    expect(schema).toContain('"/health"');
    expect(schema).toContain('getHealth');
  });

  it('is deterministic', async () => {
    const first = await generateSchema(pathToFileURL(fixture));
    const second = await generateSchema(pathToFileURL(fixture));
    expect(second).toBe(first);
  });
});

function runScript(args: readonly string[]): { status: number | null; stderr: string } {
  const result = spawnSync(process.execPath, [script, ...args], { encoding: 'utf8' });
  return { status: result.status, stderr: result.stderr };
}

describe('scripts/generate.ts', () => {
  it('fails with a clear message for a missing document', () => {
    const result = runScript(['--input', join(tmpdir(), 'stuffcloud-no-such-openapi.json')]);
    expect(result.status).toBe(1);
    expect(result.stderr).toContain('OpenAPI document not found');
  });

  it('fails on bad arguments', () => {
    const result = runScript([]);
    expect(result.status).toBe(1);
    expect(result.stderr).toContain('missing --input');
  });

  it('--check fails while the file is missing or stale and passes once it is written', async () => {
    const before = await readFile(generatedFile, 'utf8').catch(() => undefined);
    try {
      await rm(generatedFile, { force: true });
      const missing = runScript(['--input', fixture, '--check']);
      expect(missing.status).toBe(1);
      expect(missing.stderr).toContain('is stale');

      expect(runScript(['--input', fixture]).status).toBe(0);
      expect(runScript(['--input', fixture, '--check']).status).toBe(0);

      await writeFile(generatedFile, '// edited by hand\n', 'utf8');
      const drifted = runScript(['--input', fixture, '--check']);
      expect(drifted.status).toBe(1);
      expect(drifted.stderr).toContain('is stale');
    } finally {
      if (before === undefined) {
        await rm(generatedFile, { force: true });
      } else {
        await writeFile(generatedFile, before, 'utf8');
      }
    }
  });
});
